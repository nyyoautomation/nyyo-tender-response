  function citeChip(id) {
    if (!id) return "";
    const doc = state.kbDocs.find((d) => d.id === id);
    if (!doc) return "";
    return ` <span class="cite">${escapeHtml(doc.source)} · ${T.page}${doc.page}</span>`;
  }

  async function generatePack() {
    setStep(3);
    state.form = readForm();
    setStep(4);
    const panel = $("#panelPack");
    panel.classList.remove("hidden");
    const out = $("#proposalOut");
    out.innerHTML = `<p class="cursor-blink" style="color:var(--muted);font-size:0.84rem">${T.drafting}</p>`;
    panel.scrollIntoView({ behavior: "smooth", block: "start" });

    const scoring = state.extraction.scoring;
    const sections = state.sections;
    out.innerHTML = "";

    // Inject form-driven bullets into C3/C4/C5
    const formBits = {
      C3: [
        {
          text: T.pmLine(state.form.pm),
          cite: state.form.pm.includes("Samira") ? "kb-cv-pm" : null,
        },
      ],
      C4: [
        {
          text: T.closureLine(state.form.weeks),
          cite: "kb-programme",
        },
      ],
      C5: [
        {
          text: T.priceLine(T.money(state.form.price)),
          cite: null,
        },
        {
          text:
            state.form.variant === "yes"
              ? T.variantYes
              : T.variantNo,
          cite: null,
        },
      ],
    };

    for (const c of scoring) {
      const sec = sections[c.id];
      const el = document.createElement("div");
      el.className = "prop-sec";
      el.innerHTML = `<h3><span class="pill">${escapeHtml(c.id)} · ${c.weight}%</span> ${escapeHtml(
        sec.title
      )}</h3><ul></ul>`;
      out.appendChild(el);
      await sleep(220);
      el.classList.add("show");
      const ul = $("ul", el);
      const bullets = [...(sec.bullets || []), ...(formBits[c.id] || [])];
      if (c.id === "C4" && state.form.notes) {
        bullets.push({ text: T.notes + state.form.notes, cite: null });
      }
      for (let i = 0; i < bullets.length; i++) {
        const b = bullets[i];
        const li = document.createElement("li");
        li.style.animationDelay = i * 0.08 + "s";
        li.innerHTML = escapeHtml(b.text) + citeChip(b.cite);
        ul.appendChild(li);
        if (b.cite) state.covered.add(b.cite);
        await sleep(120);
      }
    }

    buildMatrix();
    buildChecklist();
    await animateRing(Math.min(96, 55 + state.covered.size * 3));
    state.packReady = true;
    icons();
  }

  function mapReqToCite(req) {
    const q = req.category + " " + req.text;
    const hits = window.NyyoBM25.score(state.kbIndex, q).slice(0, 1);
    if (hits[0]) {
      const doc = state.kbDocs.find((d) => d.id === hits[0].id);
      return doc ? `${doc.source} · ${T.page}${doc.page}` : "—";
    }
    return T.manual;
  }

  function buildMatrix() {
    const tb = $("#matrix tbody");
    tb.innerHTML = state.extraction.requirements
      .map((r) => {
        const cite = mapReqToCite(r);
        const status =
          cite === T.manual
            ? `<span class="pill warn">${T.needsReview}</span>`
            : `<span class="pill ok">${T.mapped}</span>`;
        return `<tr>
          <td class="mono">${escapeHtml(r.id)}</td>
          <td>${escapeHtml(r.text.slice(0, 120))}${r.text.length > 120 ? "…" : ""}</td>
          <td>${status}</td>
          <td class="cite">${escapeHtml(cite)}</td>
        </tr>`;
      })
      .join("");
  }

  function buildChecklist() {
    const tb = $("#checklist tbody");
    const auto = {
      D3: T.chkD3,
      D4: state.form ? T.chkD4(T.money(state.form.price)) : T.chkD4none,
      D5: state.form ? T.chkD5(state.form.pm) : T.chkD5none,
      D10: state.form && state.form.variant === "yes" ? T.chkD10yes : T.chkD10no,
    };
    tb.innerHTML = state.extraction.required_documents
      .map((d) => {
        const note = auto[d.id] || (d.mandatory ? T.attach : T.optional);
        const ok = ["D3", "D4", "D5"].includes(d.id);
        return `<tr><td>${escapeHtml(d.name)}</td><td>${
          ok ? '<span class="pill ok">' : '<span class="pill warn">'
        }${escapeHtml(note)}</span></td></tr>`;
      })
      .join("");
  }

  /* ---------- DOCX export ---------- */
  async function downloadDocx() {
    if (!state.packReady) await generatePack();
    const D = window.docx;
    if (!D) {
      alert(T.docxLoading);
      return;
    }
    const { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, WidthType, BorderStyle } =
      D;
    const form = state.form || readForm();
    const children = [
      new Paragraph({
        text: T.docxTitle,
        heading: HeadingLevel.TITLE,
      }),
      new Paragraph({
        children: [
          new TextRun({
            text: T.docxWarn,
            bold: true,
            color: "B45309",
          }),
        ],
      }),
      new Paragraph({
        text: `${state.extraction.meta.title} · ${state.extraction.meta.tender_id}`,
        spacing: { after: 200 },
      }),
      new Paragraph({
        text: T.docxInputs(form, T.money(form.price)),
        spacing: { after: 300 },
      }),
    ];

    for (const c of state.extraction.scoring) {
      const sec = state.sections[c.id];
      children.push(
        new Paragraph({
          text: `${c.id} (${c.weight}%) — ${sec.title}`,
          heading: HeadingLevel.HEADING_1,
        })
      );
      const extras = [];
      if (c.id === "C3") extras.push(T.docxPm(form.pm));
      if (c.id === "C4") {
        extras.push(T.docxClosure(form.weeks));
        if (form.notes) extras.push(T.notes + form.notes);
      }
      if (c.id === "C5") {
        extras.push(T.docxPrice(T.money(form.price)));
        extras.push(form.variant === "yes" ? T.docxVarYes : T.docxVarNo);
      }
      for (const b of [...sec.bullets, ...extras.map((t) => ({ text: t, cite: null }))]) {
        const cite =
          b.cite && state.kbDocs.find((d) => d.id === b.cite)
            ? ` [${state.kbDocs.find((d) => d.id === b.cite).source} ${T.page}${state.kbDocs.find((d) => d.id === b.cite).page}]`
            : "";
        children.push(
          new Paragraph({
            text: `• ${typeof b === "string" ? b : b.text}${cite}`,
            spacing: { after: 80 },
          })
        );
      }
    }

    children.push(new Paragraph({ text: T.matrix, heading: HeadingLevel.HEADING_1 }));
    const border = { style: BorderStyle.SINGLE, size: 4, color: "CCCCCC" };
    const borders = { top: border, bottom: border, left: border, right: border };
    const headerRow = new TableRow({
      children: T.hdr.map(
        (t) =>
          new TableCell({
            borders,
            width: { size: 2000, type: WidthType.DXA },
            children: [new Paragraph({ children: [new TextRun({ text: t, bold: true })] })],
          })
      ),
    });
    const rows = state.extraction.requirements.map((r) => {
      const cite = mapReqToCite(r);
      return new TableRow({
        children: [r.id, r.text.slice(0, 160), cite].map(
          (t) =>
            new TableCell({
              borders,
              width: { size: 2000, type: WidthType.DXA },
              children: [new Paragraph(String(t))],
            })
        ),
      });
    });
    children.push(
      new Table({
        width: { size: 9000, type: WidthType.DXA },
        rows: [headerRow, ...rows],
      })
    );

    children.push(new Paragraph({ text: T.checklist, heading: HeadingLevel.HEADING_1 }));
    for (const d of state.extraction.required_documents) {
      children.push(
        new Paragraph({
          text: `☐ ${d.name}${d.mandatory ? T.reqd : T.opt} — ${d.notes || ""}`,
          spacing: { after: 60 },
        })
      );
    }

    children.push(
      new Paragraph({
        text: T.footer,
        spacing: { before: 400 },
      })
    );

    const doc = new Document({
      creator: "Nyyo Automation",
      title: T.docTitle,
      sections: [{ children }],
    });
    const blob = await Packer.toBlob(doc);
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = T.file + ".docx";
    a.click();
    URL.revokeObjectURL(a.href);
  }

  /* ---------- PDF via print ---------- */
  function exportPdf() {
    if (!state.packReady) {
      alert(T.genFirst);
      return;
    }
    const root = $("#printRoot");
    root.classList.remove("hidden");
    root.innerHTML = `<div style="font-family:Inter,system-ui,sans-serif;padding:24px;color:#111;background:#fff">
      <h1>${T.printTitle}</h1>
      <p style="color:#b45309;font-weight:700">${T.printWarn}</p>
      <p>${escapeHtml(state.extraction.meta.title)} · ${escapeHtml(state.extraction.meta.tender_id)}</p>
      ${$("#proposalOut").innerHTML}
      <h2>${T.matrix}</h2>
      ${$("#matrix").outerHTML}
      <h2>${T.checklist}</h2>
      ${$("#checklist").outerHTML}
    </div>`;
    const prev = document.title;
    document.title = T.file;
    window.print();
    document.title = prev;
    setTimeout(() => {
      root.classList.add("hidden");
      root.innerHTML = "";
    }, 500);
  }

