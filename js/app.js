  function countUp(el, to, ms) {
    const t0 = performance.now();
    (function f(t) {
      const k = Math.min(1, (t - t0) / ms);
      el.textContent = Math.round(to * k) + "%";
      if (k < 1) requestAnimationFrame(f);
    })(t0);
  }

